/// Every task of a built milestone has at least one test whose name starts
/// with its id, unless its plan section holds the line `**Tests:** manual`.
/// A project with no plan files has nothing to trace, and the check passes.
///
/// Usage:
///   dart run tool/traceability.dart          writes docs/traceability.yaml
///   dart run tool/traceability.dart --check  fails on a gap or a stale file
library;

import 'dart:io';

/// Milestones whose tasks must all be traced. `KIT` is the starter kit's own
/// task ids (`KIT-T7`). A project adds its milestone, such as `M1`, in that
/// milestone's exit-gate task.
const builtMilestones = <String>['KIT'];

const plansDir = 'docs/superpowers/plans';
const outputPath = 'docs/traceability.yaml';

final _manualMarker = RegExp(r'^\*\*Tests:\*\* manual\s*$', multiLine: true);

/// A task id: `KIT`, or a milestone number with an optional letter for a
/// follow-up plan of the same milestone (`M2R`), then the task number.
const _taskId = r'(?:KIT|M\d+[A-Z]?)-T\d+';

final _heading = RegExp('^### Task ($_taskId):', multiLine: true);
final _testName = RegExp(
  r'''\b(?:test|testWidgets|group|blocTest(?:<[^>]*>)?)\(\s*r?['"]('''
  '$_taskId'
  '):',
);

class TaskTrace {
  const TaskTrace(this.id, {required this.manual, required this.tests});

  final String id;
  final bool manual;
  final List<String> tests;

  String get milestone => id.split('-').first;
}

/// Task ids in [plan], each with whether its section is marked manual.
Map<String, bool> planTasks(String plan) {
  final matches = _heading.allMatches(plan).toList();
  return {
    for (var i = 0; i < matches.length; i++)
      matches[i].group(1)!: plan
          .substring(
            matches[i].end,
            i + 1 < matches.length ? matches[i + 1].start : plan.length,
          )
          .contains(_manualMarker),
  };
}

/// The test files naming each task id, from [testFiles] keyed by path.
Map<String, Set<String>> testsByTask(Map<String, String> testFiles) {
  final found = <String, Set<String>>{};
  testFiles.forEach((path, content) {
    for (final match in _testName.allMatches(content)) {
      found.putIfAbsent(match.group(1)!, () => <String>{}).add(path);
    }
  });
  return found;
}

List<TaskTrace> trace(
  Map<String, bool> tasks,
  Map<String, Set<String>> tests,
) => [
  for (final MapEntry(key: id, value: manual) in tasks.entries)
    TaskTrace(
      id,
      manual: manual,
      tests: (tests[id]?.toList() ?? <String>[])..sort(),
    ),
];

List<String> gaps(List<TaskTrace> traces, List<String> built) => [
  for (final t in traces)
    if (built.contains(t.milestone) && !t.manual && t.tests.isEmpty) t.id,
];

String toYaml(List<TaskTrace> traces) {
  final out = StringBuffer(
    '# Generated by tool/traceability.dart. Do not edit.\n',
  );
  for (final t in traces) {
    out
      ..writeln('${t.id}:')
      ..writeln('  kind: ${t.manual ? 'manual' : 'automated'}');
    if (t.tests.isEmpty) {
      out.writeln('  tests: []');
    } else {
      out.writeln('  tests:');
      for (final path in t.tests) {
        out.writeln('    - $path');
      }
    }
  }
  return out.toString();
}

void main(List<String> args) {
  final plansFolder = Directory(plansDir);
  final plans = plansFolder.existsSync()
      ? (plansFolder
            .listSync()
            .whereType<File>()
            .where((f) => f.path.endsWith('.md'))
            .toList()
          ..sort((a, b) => a.path.compareTo(b.path)))
      : <File>[];
  final tasks = <String, bool>{};
  for (final plan in plans) {
    tasks.addAll(planTasks(plan.readAsStringSync()));
  }
  if (tasks.isEmpty) {
    stdout.writeln('No plan files, nothing to trace.');
    return;
  }
  final testFolder = Directory('test');
  final testFiles = {
    for (final f
        in testFolder.existsSync()
            ? testFolder.listSync(recursive: true).whereType<File>()
            : <File>[])
      if (f.path.endsWith('_test.dart'))
        f.path.replaceAll(r'\', '/'): f.readAsStringSync(),
  };
  final traces = trace(tasks, testsByTask(testFiles));
  final yaml = toYaml(traces);
  final file = File(outputPath);
  if (!args.contains('--check')) {
    file.writeAsStringSync(yaml);
    stdout.writeln('Wrote $outputPath (${traces.length} tasks).');
    return;
  }
  final missing = gaps(traces, builtMilestones);
  if (missing.isNotEmpty) {
    stderr.writeln('Tasks with no test: ${missing.join(', ')}');
    exitCode = 1;
  }
  if (!file.existsSync() || file.readAsStringSync() != yaml) {
    stderr.writeln(
      '$outputPath is stale. Run: dart run tool/traceability.dart',
    );
    exitCode = 1;
  }
  if (exitCode == 0) stdout.writeln('${traces.length} tasks traced.');
}
